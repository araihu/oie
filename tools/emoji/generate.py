"""Build local emoji catalogs from pinned Unicode 17.0 and CLDR 48 data.

Run from the repository root. --cache can reuse downloaded source files;
every input is verified before parsing, including cached files.
"""
import argparse
import hashlib
import json
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET

CLDR = "https://raw.githubusercontent.com/unicode-org/cldr/release-48/"
SOURCES = {
    "emoji-test.txt": ("https://www.unicode.org/Public/17.0.0/emoji/emoji-test.txt", "1d8a944f88d7952f7ef7c5167fef3c67995bcae24543949710231b03a201acda"),
    "en.xml": (CLDR + "common/annotations/en.xml", "8511aadd046fdba2f0ffe590266ced8bbf48175ad139b2675d85d7141057b235"),
    "en-derived.xml": (CLDR + "common/annotationsDerived/en.xml", "d76bd041c8c9e7b00b716aff8b7d9dbf509877010e191d5efd068be2553e066e"),
    "pt.xml": (CLDR + "common/annotations/pt.xml", "784be701f969963dc1d8240cd8ae02eb5bad28153bc9d0613e5c5777537e5398"),
    "pt-derived.xml": (CLDR + "common/annotationsDerived/pt.xml", "8810bb38da561be161413f6292a6ce4a81d815ae9b6906a16a5b38d89f398496"),
    "LICENSE.txt": (CLDR + "LICENSE", "b4c0ae8ef04f7059f96ce5bbe0467f9fe6f6d81bbe13517701dfeb961fb4d0b6"),
}
GROUPS = ["Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink", "Travel & Places", "Activities", "Objects", "Symbols", "Flags"]
# Mixed-tone sequences use expanded forms of these original emoji.
FAMILY_EQUIVALENTS = {
    "🫱‍🫲": "🤝", "🧑‍🐰‍🧑": "👯", "👨‍🐰‍👨": "👯‍♂️", "👩‍🐰‍👩": "👯‍♀️",
    "🧑‍🫯‍🧑": "🤼", "👨‍🫯‍👨": "🤼‍♂️", "👩‍🫯‍👩": "🤼‍♀️",
    "👩‍🤝‍👩": "👭", "👩‍🤝‍👨": "👫", "👨‍🤝‍👨": "👬",
    "🧑‍❤‍💋‍🧑": "💏", "🧑‍❤‍🧑": "💑",
}


def without_tone(glyph):
    return "".join(char for char in glyph if char != "\ufe0f" and not 0x1F3FB <= ord(char) <= 0x1F3FF)


def generate(cache, output):
    cache.mkdir(parents=True, exist_ok=True)
    inputs = {}
    for name, (url, digest) in SOURCES.items():
        source = cache / name
        if not source.exists():
            with urllib.request.urlopen(url, timeout=30) as response:
                source.write_bytes(response.read())
        data = source.read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError("Unicode input checksum mismatch: " + name)
        inputs[name] = data
    annotations = {}
    for language in ["en", "pt"]:
        names, keywords = {}, {}
        for name in [language + ".xml", language + "-derived.xml"]:
            for item in ET.fromstring(inputs[name]).iter("annotation"):
                key, text = item.attrib["cp"], item.text or ""
                if item.attrib.get("type") == "tts":
                    names[key] = text
                else:
                    keywords[key] = text
        annotations[language] = names, keywords
    aliases = json.loads(Path(__file__).with_name("aliases.json").read_text())
    glyphs = []
    group = ""
    for line in inputs["emoji-test.txt"].decode().splitlines():
        if line.startswith("# group: "):
            group = line.removeprefix("# group: ")
        if "; fully-qualified" not in line or group not in GROUPS:
            continue
        codes = line.split(";", 1)[0].split()
        glyph = "".join(chr(int(code, 16)) for code in codes)
        glyphs.append((glyph, GROUPS.index(group)))
    roots = {without_tone(glyph): glyph for glyph, _ in glyphs if not any(0x1F3FB <= ord(char) <= 0x1F3FF for char in glyph)}
    families = {}
    for glyph, _ in glyphs:
        normalized = without_tone(glyph)
        base = FAMILY_EQUIVALENTS.get(normalized) or roots.get(normalized)
        if not base:
            raise ValueError("Missing variant family root: " + glyph)
        if glyph != base:
            families[glyph] = base
    catalogs = {"en": [], "pt-BR": []}
    for glyph, group in glyphs:
        key = glyph.replace("\ufe0f", "")
        search_terms = []
        for names, keywords in annotations.values():
            search_terms.extend([names.get(key, ""), keywords.get(key, "")])
        search_terms.extend(aliases.get(families.get(glyph, glyph), []))
        combined = " | ".join(dict.fromkeys(search_terms))
        for locale, language in [("en", "en"), ("pt-BR", "pt")]:
            names, keywords = annotations[language]
            if key not in names:
                raise ValueError("Missing localized annotation: " + locale + " " + glyph)
            catalogs[locale].append([glyph, names[key], combined, group])
    output.mkdir(parents=True, exist_ok=True)
    for locale, items in catalogs.items():
        body = {"unicode": "17.0", "cldr": "48", "locale": locale, "license": "Unicode-3.0", "copyright": "Copyright © 1991-2025 Unicode, Inc.", "notice": "Modified Unicode data: compact emoji-only catalog generated by Oie, with Oie search aliases. See /ui/emoji/LICENSE.txt.", "families": families, "items": items}
        (output / (locale + ".json")).write_text(json.dumps(body, ensure_ascii=False, separators=(",", ":")) + "\n")
        print(locale, len(items), "emojis")
    (output / "LICENSE.txt").write_bytes(inputs["LICENSE.txt"])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=Path("/tmp/oie-emoji-unicode48"))
    parser.add_argument("--output", type=Path, default=Path("internal/adapters/web/emoji"))
    args = parser.parse_args()
    generate(args.cache, args.output)
