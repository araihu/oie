// Command generate-oiectl generates the client and commands. Oiê owns the entry point.
package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"

	"github.com/araihu/oapi-cli-gen/generator"
	"go.yaml.in/yaml/v3"
	"golang.org/x/mod/modfile"
)

func run(check bool, expectedVersion string) error {
	// This tool is invoked from the tools module.
	if err := os.Chdir(".."); err != nil {
		return err
	}
	const cliSpec = "api/openapi.cli.json"
	if expectedVersion != "" {
		data, err := os.ReadFile("api/openapi.yaml")
		if err != nil {
			return err
		}
		var spec struct{ Info struct{ Version string } }
		if err := yaml.Unmarshal(data, &spec); err != nil {
			return err
		}
		if spec.Info.Version != expectedVersion {
			return fmt.Errorf("api/openapi.yaml: info.version is %q, expected %q", spec.Info.Version, expectedVersion)
		}
	}
	module, err := os.ReadFile("cli/go.mod")
	if err != nil {
		return err
	}
	result, err := generator.Generate(context.Background(), generator.Options{
		Spec: cliSpec, Name: "oiectl", Module: modfile.ModulePath(module),
	})
	if err != nil {
		return err
	}
	data, err := os.ReadFile(cliSpec)
	if err != nil {
		return err
	}
	var spec struct {
		Info          struct{ Version string }
		Documentation map[string]string `json:"x-cli-local-problem-documentation"`
	}
	if err := json.Unmarshal(data, &spec); err != nil {
		return err
	}
	if expectedVersion != "" && spec.Info.Version != expectedVersion {
		return fmt.Errorf("%s: info.version is %q, expected %q", cliSpec, spec.Info.Version, expectedVersion)
	}
	const entrypoint = "cmd/oiectl/main.go"
	// Keep a generator-owned file at the original path to preserve manifest
	// validation and continue taking diagnostic links from the OpenAPI overlay.
	documentation, err := format.Source(fmt.Appendf(nil, "// Code generated by generate-oiectl. DO NOT EDIT.\n\npackage main\n\nvar localProblemDocumentation = %#v\n", spec.Documentation))
	if err != nil {
		return err
	}
	result.Files[entrypoint] = documentation
	if check {
		return result.Check("cli")
	}
	return result.Write("cli", true)
}

func main() {
	check := flag.Bool("check", false, "Check generated files without updating them")
	expectedVersion := flag.String("spec-version", "", "Require this OpenAPI info.version")
	flag.Parse()
	if err := run(*check, *expectedVersion); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
