// Command generate-pdfjs-embed pins the embedded PDF.js inventory to Muamba's lock.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"go.yaml.in/yaml/v3"
)

const (
	webDirectory = "internal/adapters/web"
	resourceID   = "pdfjs/display"
)

func main() {
	check := flag.Bool("check", false, "check the inventory and generated Go file")
	flag.Parse()
	log.SetFlags(0)
	if err := generate("..", *check); err != nil {
		log.Fatal(err)
	}
}

func generate(root string, check bool) error {
	data, err := os.ReadFile(filepath.Join(root, ".muamba.lock.yaml"))
	if err != nil {
		return err
	}
	var lock struct {
		Directories []struct {
			ID    string `yaml:"id"`
			Files []struct {
				Path string `yaml:"path"`
			} `yaml:"files"`
		} `yaml:"directories"`
	}
	if err := yaml.Unmarshal(data, &lock); err != nil {
		return err
	}
	locked := make(map[string]bool)
	for _, directory := range lock.Directories {
		if directory.ID != resourceID {
			continue
		}
		for _, file := range directory.Files {
			name, ok := strings.CutPrefix(file.Path, webDirectory+"/")
			if !ok || !strings.HasPrefix(name, "pdfjs/") || !fs.ValidPath(name) || strings.ContainsAny(name, "*?[\\") {
				return fmt.Errorf("invalid locked PDF.js path: %q", file.Path)
			}
			if locked[name] {
				return fmt.Errorf("duplicate locked PDF.js path: %q", file.Path)
			}
			locked[name] = true
		}
	}
	if len(locked) == 0 {
		return fmt.Errorf("no files in Muamba's %s lock", resourceID)
	}

	web := filepath.Join(root, webDirectory)
	files := make([]string, 0, len(locked))
	err = fs.WalkDir(os.DirFS(web), "pdfjs", func(name string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		if !entry.Type().IsRegular() || !locked[name] {
			return fmt.Errorf("PDF.js file is not a regular file listed in Muamba's lock: %s", name)
		}
		files = append(files, name)
		return nil
	})
	if err != nil {
		return err
	}
	if len(files) != len(locked) {
		return fmt.Errorf("PDF.js file inventory differs from Muamba's lock: found %d, expected %d", len(files), len(locked))
	}
	slices.Sort(files)

	var output bytes.Buffer
	fmt.Fprint(&output, "// Code generated by generate-pdfjs-embed. DO NOT EDIT.\n\npackage web\n\nimport \"embed\"\n\n")
	for _, file := range files {
		fmt.Fprintf(&output, "//go:embed %q\n", file)
	}
	fmt.Fprintln(&output, "var pdfJSAssets embed.FS")
	destination := filepath.Join(web, "pdfjs_embed_gen.go")
	if !check {
		return os.WriteFile(destination, output.Bytes(), 0o644)
	}
	current, err := os.ReadFile(destination)
	if err != nil {
		return err
	}
	if !bytes.Equal(current, output.Bytes()) {
		return fmt.Errorf("%s differs from Muamba's lock. Run make generate-pdfjs-embed", destination)
	}
	return nil
}
