#!/usr/bin/env python3
"""Derive protocol validation bases from Oie's pinned Unicode emoji catalog."""
import argparse
import json
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parent.parent
catalog = json.loads((root / 'internal/adapters/web/emoji/en.json').read_text())
values = [item[0] for item in catalog['items']] + list(catalog['families'])
bases = sorted({ord(char) for value in values for char in value
                if ord(char) >= 0xA0 and ord(char) not in (0xFE0F, 0x200D, 0x20E3)
                and not 0x1F3FB <= ord(char) <= 0x1F3FF
                and not 0x1F1E6 <= ord(char) <= 0x1F1FF
                and not 0xE0020 <= ord(char) <= 0xE007F})
ranges = []
for value in bases:
    if ranges and ranges[-1][1] == value - 1:
        ranges[-1][1] = value
    else:
        ranges.append([value, value])
output = '''// Code generated by tools/generate-reaction-emoji-bases.py. DO NOT EDIT.
// Unicode 17.0 emoji base data, derived from the bundled catalog.
// Copyright © 1991-2025 Unicode, Inc. Distributed under Unicode-3.0.
// See internal/adapters/web/emoji/LICENSE.txt.
package application

import "sort"

var reactionEmojiBaseRanges = [...][2]rune{
'''
output += ''.join(f'\t{{0x{start:x}, 0x{end:x}}},\n' for start, end in ranges)
output += '''}

func reactionEmojiBase(value rune) bool {
 index := sort.Search(len(reactionEmojiBaseRanges), func(i int) bool { return reactionEmojiBaseRanges[i][1] >= value })
 return index < len(reactionEmojiBaseRanges) && reactionEmojiBaseRanges[index][0] <= value
}
'''
output = subprocess.run(['gofmt'], input=output, text=True, capture_output=True, check=True).stdout
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail if committed data differs without rewriting it')
args = parser.parse_args()
destination = root / 'internal/application/reaction_emoji_bases.go'
if args.check:
    if not destination.exists() or destination.read_text() != output:
        raise SystemExit('Reaction emoji bases are outdated; run tools/generate-reaction-emoji-bases.py')
else:
    destination.write_text(output)
